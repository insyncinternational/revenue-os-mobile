/**
 * Builds src/i18n/<lang>.generated.ts (az, ar) from the web's dictionaries, keeping only the strings this
 * app uses. The web dictionaries are keyed by the English text (revenue-os-frontend/lib/i18n/locales/
 * <lang>.json, with <lang>.manual.json overriding it), so the app and the web always say the same thing.
 * The web's extractor (scripts/i18n/extract.mjs) also collects this app's en.ts, so `npm run i18n:check`
 * there reports anything missing here.
 *
 * Usage: npm run i18n:sync
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const webLocales = join(root, "..", "revenue-os-frontend", "lib", "i18n", "locales");
const LANGS = ["az", "ar"];

// Pull the English values out of en.ts without a TypeScript toolchain: every `"key": "value",` line.
const enSource = readFileSync(join(root, "src", "i18n", "en.ts"), "utf8");
// Distinct texts: several keys can share one English string.
const english = [...new Set([...enSource.matchAll(/^\s*"[^"]+":\s*"((?:[^"\\]|\\.)*)",?\s*$/gm)].map((m) => JSON.parse(`"${m[1]}"`)))];

const readJson = (f) => (existsSync(f) ? JSON.parse(readFileSync(f, "utf8")) : {});
const norm = (s) => s.replace(/\s+/g, " ").trim();

for (const lang of LANGS) {
  const dict = { ...readJson(join(webLocales, `${lang}.json`)), ...readJson(join(webLocales, `${lang}.manual.json`)) };
  const out = {};
  const missing = [];
  for (const s of english) {
    // The web dictionary normalises whitespace in its keys.
    const v = dict[s] ?? dict[norm(s)];
    if (typeof v === "string" && v.trim()) out[s] = v;
    else missing.push(s);
  }
  const body = Object.entries(out)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`)
    .join("\n");
  writeFileSync(
    join(root, "src", "i18n", `${lang}.generated.ts`),
    `/* Generated by scripts/sync-locales.mjs from the web's ${lang} dictionary. Do not edit by hand. */\nexport const ${lang}: Readonly<Record<string, string>> = {\n${body}\n};\n`,
  );
  console.log(`${lang}: ${Object.keys(out).length}/${english.length} strings translated.`);
  if (missing.length) console.log(`Missing (shown in English until added to the web dictionary):\n  - ${missing.join("\n  - ")}`);
}
