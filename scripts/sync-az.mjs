/**
 * Builds src/i18n/az.generated.ts from the web's Azerbaijani dictionary, keeping only the strings this app uses.
 * The web dictionary is keyed by the English text (revenue-os-frontend/lib/i18n/locales/az.json, with
 * az.manual.json overriding it), so the app and the web always say the same thing.
 *
 * Usage: npm run i18n:sync
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const webLocales = join(root, "..", "revenue-os-frontend", "lib", "i18n", "locales");

const auto = JSON.parse(readFileSync(join(webLocales, "az.json"), "utf8"));
const manual = JSON.parse(readFileSync(join(webLocales, "az.manual.json"), "utf8"));
const dict = { ...auto, ...manual };

// Pull the English values out of en.ts without a TypeScript toolchain: every `"key": "value",` line.
const enSource = readFileSync(join(root, "src", "i18n", "en.ts"), "utf8");
const english = [...enSource.matchAll(/^\s*"[^"]+":\s*"((?:[^"\\]|\\.)*)",?\s*$/gm)].map((m) => JSON.parse(`"${m[1]}"`));

const out = {};
const missing = [];
for (const s of english) {
  if (typeof dict[s] === "string" && dict[s].trim()) out[s] = dict[s];
  else missing.push(s);
}

const body = Object.entries(out)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`)
  .join("\n");

writeFileSync(
  join(root, "src", "i18n", "az.generated.ts"),
  `/* Generated by scripts/sync-az.mjs from the web's Azerbaijani dictionary. Do not edit by hand. */\nexport const az: Readonly<Record<string, string>> = {\n${body}\n};\n`,
);

console.log(`az: ${Object.keys(out).length}/${english.length} strings translated.`);
if (missing.length) console.log(`Missing (shown in English until added to the web dictionary):\n  - ${missing.join("\n  - ")}`);
