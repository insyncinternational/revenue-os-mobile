/**
 * expo-widgets on Android only sends a widget button tap back to the widget (to change its props); it has no
 * "open the app". This rewrites each generated widget provider so a button whose target is "open:<path>" opens
 * <scheme>://<path> in the app instead, and every other target keeps the library's behaviour.
 *
 * Must run after expo-widgets writes its providers: list it BEFORE expo-widgets in app.json (dangerous mods run
 * in reverse plugin order).
 * Options: { widgets: ["TodayWidget"] } — the widget names, as in the expo-widgets config.
 */
const fs = require("fs");
const path = require("path");
const { AndroidConfig, withDangerousMod } = require("expo/config-plugins");

const providerKt = (pkg, name, scheme) => `package ${pkg}

import android.content.Context
import android.content.Intent
import android.net.Uri
import expo.modules.widgets.ExpoWidgetsAppWidgetProvider

// Generated by plugins/withWidgetOpenApp.js: an "open:<path>" button target opens ${scheme}://<path> in the app.
class ${name}Provider : ExpoWidgetsAppWidgetProvider(${JSON.stringify(name)}) {
  override fun onReceive(context: Context, intent: Intent) {
    val target = intent.getStringExtra("expo.modules.widgets.extra.TARGET")
    if (intent.action == "expo.modules.widgets.ACTION_WIDGET_INTERACTION" && target != null && target.startsWith("open:")) {
      val open = Intent(Intent.ACTION_VIEW, Uri.parse("${scheme}://" + target.removePrefix("open:").trimStart('/')))
        .setPackage(context.packageName)
        .addFlags(Intent.FLAG_ACTIVITY_NEW_TASK or Intent.FLAG_ACTIVITY_SINGLE_TOP)
      context.startActivity(open)
      return
    }
    super.onReceive(context, intent)
  }
}
`;

module.exports = function withWidgetOpenApp(config, { widgets = [] } = {}) {
  return withDangerousMod(config, [
    "android",
    async (config) => {
      const pkg = AndroidConfig.Package.getPackage(config);
      const scheme = Array.isArray(config.scheme) ? config.scheme[0] : config.scheme;
      if (!pkg || !scheme) throw new Error("withWidgetOpenApp needs android.package and scheme in app.json");
      const dir = path.join(config.modRequest.platformProjectRoot, "app/src/main/java", ...pkg.split("."));
      fs.mkdirSync(dir, { recursive: true });
      for (const name of widgets) fs.writeFileSync(path.join(dir, `${name}Provider.kt`), providerKt(pkg, name, scheme));
      return config;
    },
  ]);
};
